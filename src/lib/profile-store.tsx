/* ---------- Stored-profile sanitising ----------
 * localStorage can hold data written by older builds (or a partially failed
 * write). Coerce every collection back to its expected shape so screens never
 * crash on `.map` / `.length` of a non-array.
 */

function asArray<T>(value: unknown): T[] {
  return Array.isArray(value) ? (value as T[]) : [];
}

function asRecord<T>(value: unknown): Record<string, T> {
  return value && typeof value === "object" && !Array.isArray(value)
    ? (value as Record<string, T>)
    : {};
}

export function sanitizeProfile(raw: unknown): Profile {
  const p = (raw && typeof raw === "object" ? raw : {}) as Record<string, unknown>;

  const byCourse = asRecord<AIQuestion[]>(p.aiQuestionsByCourse);
  for (const key of Object.keys(byCourse)) {
    byCourse[key] = asArray<AIQuestion>(byCourse[key]);
  }
  // Legacy flat list: attribute it to the in-progress course if we can tell,
  // otherwise drop it rather than risk serving it for the wrong course.
  const legacy = asArray<AIQuestion>(p.aiQuestions);
  const legacyCourse = (p.inProgressTest as { courseCode?: string } | null)?.courseCode;
  if (legacy.length && legacyCourse && !byCourse[legacyCourse]) {
    byCourse[legacyCourse] = legacy;
  }

  return {
    ...emptyProfile,
    ...(p as Partial<Profile>),
    accounts: asArray<LocalAccount>(p.accounts),
    courses: asArray<UserCourse>(p.courses),
    attempts: asArray<MockAttempt>(p.attempts),
    topicScores: asArray<TopicScore>(p.topicScores),
    masteredCourses: asArray<string>(p.masteredCourses),
    courseTestSettings: asRecord<CourseTestSettings>(p.courseTestSettings),
    courseTopicAnalysis: asRecord<CourseTopicAnalysis>(p.courseTopicAnalysis),
    aiQuestionsByCourse: byCourse,
  };
}

type Ctx = {
  profile: Profile;
  step: OnboardingStep | "dashboard";
  view: AppView;
  activeCourseCode: string | null;
  activeAttemptId: string | null;
  update: (p: Partial<Profile>) => void;
  go: (s: OnboardingStep | "dashboard") => void;
  navigate: (v: AppView, opts?: { courseCode?: string | null; attemptId?: string | null }) => void;
  resetSetup: () => void;
};

const StoreCtx = createContext<Ctx | null>(null);
const KEY = "truefluency-profile-v2";

export function ProfileProvider({ children }: { children: ReactNode }) {
  const [profile, setProfile] = useState<Profile>(emptyProfile);
  const [step, setStep] = useState<OnboardingStep | "dashboard">("splash");
  const [view, setView] = useState<AppView>("home");
  const [activeCourseCode, setActiveCourseCode] = useState<string | null>(null);
  const [activeAttemptId, setActiveAttemptId] = useState<string | null>(null);
  const [hydrated, setHydrated] = useState(false);

  useEffect(() => {
    try {
      const raw = localStorage.getItem(KEY);
      if (raw) {
        setProfile(sanitizeProfile(JSON.parse(raw)));
        // Step stays "splash": the entrance animation plays on every app open,
        // then the splash routes returning users straight to the dashboard.
      }
    } catch (err) {
      console.error("[profile-store] stored profile unreadable, starting fresh", err);
    }
    setHydrated(true);
  }, []);

  // One-time migration: older builds stored the typed password in plain text.
  // Replace it with a verifier hash plus the derived Supabase password so the
  // same account still resolves to the same cloud user.
  useEffect(() => {
    if (!hydrated) return;
    const stale = profile.accounts.filter((a) => a.password);
    if (!stale.length) return;
    let cancelled = false;
    void (async () => {
      const { deriveSupabasePassword, localPasswordVerifier } = await import(
        "@/lib/supabase-session"
      );
      const migrated = await Promise.all(
        profile.accounts.map(async (a) => {
          if (!a.password) return a;
          const [verifier, derived] = await Promise.all([
            localPasswordVerifier(a.email, a.password),
            deriveSupabasePassword(a.email, a.password),
          ]);
          return { name: a.name, email: a.email, verifier, derived };
        }),
      );
      if (!cancelled) setProfile((cur) => ({ ...cur, accounts: migrated }));
    })();
    return () => {
      cancelled = true;
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [hydrated, profile.accounts]);


  useEffect(() => {
    if (hydrated) {
      try { localStorage.setItem(KEY, JSON.stringify(profile)); } catch { /* ignore */ }
    }
  }, [profile, hydrated]);

  /* ---------- Cloud sync ----------
   * The database is the source of truth for signed-in users; localStorage is
   * an offline cache. On session start we load the cloud snapshot, or migrate
   * the existing local profile up when no cloud record exists yet. After that,
   * profile changes are written through (debounced).
   */
  const cloudReady = useRef(false);
  const profileRef = useRef(profile);
  profileRef.current = profile;

  useEffect(() => {
    if (!hydrated) return;
    let cancelled = false;

    const sync = async () => {
      const { loadCloudProfile, pushCloudProfile } = await import("@/lib/cloud-sync");
      try {
        const snapshot = await loadCloudProfile();
        if (cancelled) return;
        if (snapshot) {
          setProfile((cur) => ({ ...cur, ...snapshot }));
        } else {
          // First cloud session: migrate whatever is already on this device.
          await pushCloudProfile(profileRef.current);
        }
        cloudReady.current = true;
      } catch (err) {
        console.error("[profile-store] cloud sync failed, staying on local cache", err);
      }
    };

    void supabase.auth.getSession().then(({ data }) => {
      if (data.session) void sync();
    });

    const { data: sub } = supabase.auth.onAuthStateChange((event, session) => {
      if (!session) return;
      if (event === "SIGNED_IN" || event === "INITIAL_SESSION" || event === "USER_UPDATED") {
        if (!cloudReady.current) void sync();
      }
    });

    return () => { cancelled = true; sub.subscription.unsubscribe(); };
  }, [hydrated]);

  // Debounced write-through of every profile change.
  useEffect(() => {
    if (!hydrated || !cloudReady.current) return;
    const t = setTimeout(() => {
      void import("@/lib/cloud-sync").then(({ pushCloudProfile }) => pushCloudProfile(profile));
    }, 800);
    return () => clearTimeout(t);
  }, [profile, hydrated]);


  const update = (p: Partial<Profile>) => setProfile((cur) => ({ ...cur, ...p }));
  const go = (s: OnboardingStep | "dashboard") => {
    setStep(s);
    if (s === "dashboard") setView("home");
  };
  const navigate = (v: AppView, opts?: { courseCode?: string | null; attemptId?: string | null }) => {
    setView(v);
    if (opts && "courseCode" in opts) setActiveCourseCode(opts.courseCode ?? null);
    if (opts && "attemptId" in opts) setActiveAttemptId(opts.attemptId ?? null);
  };
  const resetSetup = () => {
    setProfile(emptyProfile);
    setStep("splash");
    setView("home");
    setActiveCourseCode(null);
    setActiveAttemptId(null);
    try { localStorage.removeItem(KEY); } catch { /* ignore */ }
  };

  return (
    <StoreCtx.Provider value={{ profile, step, view, activeCourseCode, activeAttemptId, update, go, navigate, resetSetup }}>
      {hydrated ? children : null}
    </StoreCtx.Provider>

  );
}

export function useProfile() {
  const ctx = useContext(StoreCtx);
  if (!ctx) throw new Error("useProfile must be used inside ProfileProvider");
  return ctx;
}

/* ---------- Streak + milestone helpers ---------- */

function today(): string {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}
function yesterday(): string {
  const d = new Date();
  d.setDate(d.getDate() - 1);
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}

/**
 * Update the streak after a qualifying activity (currently: mock test completion).
 * Structured so flashcards etc. can call this later without a rewrite.
 */
export function bumpStreak(p: Profile): Pick<Profile, "streakDays" | "lastQualifyingDay"> {
  const t = today();
  if (p.lastQualifyingDay === t) {
    return { streakDays: p.streakDays, lastQualifyingDay: t };
  }
  if (p.lastQualifyingDay === yesterday()) {
    return { streakDays: p.streakDays + 1, lastQualifyingDay: t };
  }
  return { streakDays: 1, lastQualifyingDay: t };
}

export function hasQualifyingActivityToday(p: Profile): boolean {
  return p.lastQualifyingDay === today();
}

export function averageForCourse(p: Profile, code: string): number | null {
  const rel = p.attempts.filter((a) => a.courseCode === code);
  if (!rel.length) return null;
  return Math.round(rel.reduce((s, a) => s + a.score, 0) / rel.length);
  }
  
